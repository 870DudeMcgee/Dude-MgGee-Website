'use strict';
const assert = require('node:assert/strict');
const { begin, commit, finish, rollbackProposal } = require('../lib/featured-drop-state');
const { createStore, STORE_ID } = require('../lib/featured-drop-store');
const { manifest, identity } = require('../lib/current-drop');
const { createMerchHandler } = require('../lib/dude-merch-route');
const fs = require('node:fs');
const initial = { format: 1, live: null, previous: null, pending: null };
const id = identity(manifest).activationId;
const started = begin(initial, manifest, null);
assert.equal(initial.pending, null);
assert.equal(started.live, null);
assert.throws(() => begin(started, manifest, null), /reconciliation/);
assert.throws(() => begin({ ...initial, live: { revision: 'newer' } }, manifest, null), /Stale/);
assert.throws(() => commit(started, 'different'), /matching/);
const committed = commit(started, id);
assert.equal(committed.pending.phase, 'READBACK');
assert.equal(committed.live.manifest.productId, manifest.productId);
assert.throws(() => begin(committed, manifest, committed.live.revision), /reconciliation/);
const completed = finish(committed, id);
assert.equal(completed.pending, null);
assert.equal(completed.live.revision, identity(manifest).revision);
assert.throws(() => begin(completed, manifest, completed.live.revision), /already active/);
const nextManifest = { ...manifest, description: 'A newly reviewed description' };
const second = finish(commit(begin(completed, nextManifest, completed.live.revision), identity(nextManifest).activationId), identity(nextManifest).activationId);
assert.deepEqual(second.previous, completed.live);
assert.equal(rollbackProposal(second, second.live.revision).restore.revision, completed.live.revision);
assert.throws(() => rollbackProposal(committed, committed.live.revision), /reconciled/);
function response() { return { headers: {}, setHeader(k,v) { this.headers[k]=v; }, status(n) { this.code=n; return this; }, send(body) { this.body=body; return this; } }; }
(async () => {
  const template = fs.readFileSync('merch.html','utf8');
  const r = response();
  await createMerchHandler(async()=>({products:[{handle:'earlier-drop',title:'Earlier product'}]}),()=>template,async()=>{throw new Error('storage offline');})({method:'GET'},r);
  assert.equal(r.code,200); assert.match(r.body,/Earlier product/); assert.match(r.body,/current feature is unavailable/); assert.doesNotMatch(r.body,/current-drop-data/); assert.equal(r.headers['Cache-Control'],'no-store');
  let writes=0;
  const store = createStore(`vercel_blob_rw_${STORE_ID}_synthetic`,async(url,options)=>{ writes++; assert.equal(options.redirect,'error'); assert.equal(options.headers['x-if-match'],'"old"'); throw new Error('uncertain transport'); });
  await assert.rejects(store.put('current.json',Buffer.from('{}'),'"old"'),/uncertain write/);
  assert.equal(writes,1,'no automatic retry');
  await assert.rejects(store.put('../other',Buffer.from('{}')),/invalid path/);
  assert.equal(writes,1);
  const conflict = createStore(`vercel_blob_rw_${STORE_ID}_synthetic`,async()=>({ok:false,status:412,json:async()=>({error:{code:'precondition_failed'}})}));
  await assert.rejects(conflict.put('current.json',Buffer.from('{}'),'"stale"'),e=>e.kind==='conflict');
  console.log('Featured-drop activation, uncertainty, rollback and catalog fallback checks passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
